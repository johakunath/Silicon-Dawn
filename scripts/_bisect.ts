import { chromium } from 'playwright-core';
import fs from 'node:fs';
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
await page.addInitScript('window.__name = (f) => f;');
await page.goto('http://localhost:5173/');
await page.waitForFunction(() => (window as any).__sd);
const json = fs.readFileSync(process.argv[2] ?? '.cache/era5.json', 'utf8');
const res = await page.evaluate((j) => {
  const g = (window as any).__sd;
  g.hud.closeModals(); (document.querySelector('#title') as HTMLElement).classList.remove('show'); (g.hud as any).openModal = null;
  g.loadJson(j); g.paused = true;
  const DAY = 240; const st = g.s; st.time = st.time - ((st.time / DAY + 0.3) % 1) * DAY + 0.97 * DAY; g.focusCore(true); g.rig.view = 12; g.viewTarget = 12;
  const sample = () => { for (let i = 0; i < 3; i++) g.tickFrame(1 / 60); const c = g.rig.renderer.domElement as HTMLCanvasElement; const gl = g.rig.renderer.getContext(); const px = new Uint8Array(4 * 9); let sum = 0; for (const [x, y] of [[0.5, 0.5], [0.3, 0.4], [0.7, 0.6]]) { gl.readPixels(Math.floor(c.width * x), Math.floor(c.height * y), 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, px); sum += px[0] + px[1] + px[2]; } return sum; };
  const out: Record<string, number> = { base: sample() };
  const kids = g.rig.scene.children;
  kids.forEach((k: any, i: number) => { const v = k.visible; k.visible = false; out[`hide${i}_${k.type}_${k.name || ''}`] = sample(); k.visible = v; });
  g.rig.bloom.enabled = false; out.noBloom = sample(); g.rig.bloom.enabled = true;
  return out;
}, json);
console.log(res);
await browser.close();
